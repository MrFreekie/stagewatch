"""Keep an installation's configuration in its own PRIVATE git repository.

The Stagewatch code repo is a blank system. Your site (devices, areas,
calibration, thresholds, dashboards, OSC targets) lives in config.yaml inside
the data folder. This tool turns the data folder into a small git repo that
tracks an explicit allow-list of site files and pushes it to a private remote,
giving you history and an off-machine backup.

Tracked (only these, anchored to the top of the data folder):
  config.yaml, README.md, .gitignore
  branding/events/<id>/logo-*.png|jpg|jpeg|webp
  contacts/*.yaml
  documents/<event>/index.json and documents/<event>/<doc>/r*.md
  documents/templates/**/index.json and documents/templates/**/r*.md
Never tracked: config.yaml.bak and any *.bak (including the *.pre-v*.bak safety copies), *.tmp
and other temp files, *.invalid*.yaml, emulate/, backups/, logs/, secret.key, the
history database with its -wal/-shm files, and updater state.
`push` rewrites .gitignore from this list each time and stops tracking anything
it now excludes. Untracking does not remove files from history already pushed.

config.yaml contains the admin PIN hash and ESPHome API encryption keys, and
contacts/documents hold personal data, so the remote MUST be private. `init` and
`push` check every URL that would be pushed to. They refuse a public GitHub repo,
and refuse any remote they cannot verify as GitHub unless you pass
--allow-unverified-remote (then you are responsible for it being private).

Usage:
    uv run python scripts/site_config.py init  [--data-dir DIR] --remote URL [--allow-unverified-remote]
    uv run python scripts/site_config.py push  [--data-dir DIR] [-m "message"] [--allow-unverified-remote]
    uv run python scripts/site_config.py pull  [--data-dir DIR]
    uv run python scripts/site_config.py status [--data-dir DIR]

--data-dir defaults to the same folder Stagewatch uses ($STAGEWATCH_DATA or the
per-user default). For the Windows boot service use C:\\ProgramData\\Stagewatch;
for the Pi service /var/lib/stagewatch.
Stop Stagewatch before `pull`, then start it again to load the pulled config.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlsplit

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from stagewatch.__main__ import default_data_dir  # noqa: E402

